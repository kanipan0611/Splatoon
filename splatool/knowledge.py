def get_rule_based_advice(mode: str | None, weapon_class: str | None) -> str:
    """APIキーがない場合のフォールバック用アドバイス生成。"""
    parts: list[str] = []
    if mode and mode in MODE_TIPS:
        parts.append(f"### {mode}の立ち回り\n" + "\n".join(f"- {t}" for t in MODE_TIPS[mode]))
    if weapon_class and weapon_class in WEAPON_TIPS:
        parts.append(
            f"### {weapon_class}のコツ\n" + "\n".join(f"- {t}" for t in WEAPON_TIPS[weapon_class])
        )
    parts.append("### 共通の上達ポイント\n" + "\n".join(f"- {t}" for t in GENERAL_TIPS[:4]))
    return "\n\n".join(parts)
